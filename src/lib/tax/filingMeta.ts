/** ID로 메타 가져오기 (없으면 undefined) */
export function getFilingMeta(eventId: string): FilingGuideMeta | undefined {
  // 매월 반복 이벤트는 ID 끝에 -월 붙음 (withholding-monthly-3 등)
  const baseId = eventId.replace(/-\d+$/, "");
  return FILING_META[baseId] ?? FILING_META[eventId];
}
